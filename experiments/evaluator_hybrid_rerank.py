"""
Evaluator for hybrid RAG experiment with BGE-M3 + BM25 + RRF + reranking.

This script:
1. Loads the clean evaluation dataset
2. For each question, retrieves top-k chunks using hybrid retrieval:
   - dense BGE-M3 retrieval from existing ChromaDB
   - BM25 sparse retrieval over baseline chunks
   - RRF fusion
   - BGE reranker
3. Generates an answer using GPT-4o-mini
4. Evaluates the answer using Claude Opus as judge
5. Computes retrieval metrics: Recall@k and MAP
6. Saves detailed results and aggregated metrics
"""

