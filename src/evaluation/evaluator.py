"""
Evaluator for RAG experiments.

This script:
1. Loads the clean evaluation dataset
2. For each question, retrieves top-k chunks using the existing RAG pipeline
3. Generates an answer using GPT-4o-mini
4. Evaluates the answer using Claude Opus as judge (4 quality aspects + error type)
5. Computes retrieval metrics (Hit Rate, Full Hit Rate for multi-chunk, MRR)
6. Saves detailed results and aggregated metrics
"""

import json
import os
import sys
import time
from collections import defaultdict
from typing import Any, Dict, List, Optional

import anthropic
from dotenv import load_dotenv
from openai import OpenAI

sys.path.append(os.path.join(os.path.dirname(__file__), "..", "generation"))
from generator import get_collection, retrieve, build_prompt, generate_answer


# =========================
# Configuration
# =========================

EVAL_DATASET_PATH = "data/evaluation/eval_dataset_enriched.json"
CHROMA_PATH = "data/chroma/baseline"
COLLECTION_NAME = "history_baseline"
RESULTS_PATH = "experiments/results/results_final_baseline.json"
METRICS_PATH = "experiments/results/metrics_final_baseline.json"

EXPERIMENT_NAME = "baseline k=10"
CHUNK_SIZE = 512
OVERLAP = 50

TOP_K = 5
GENERATOR_MODEL = "gpt-4o-mini"
JUDGE_MODEL = "claude-opus-4-5"
JUDGE_RETRIES = 2


# =========================
# Judge Prompt
# =========================

JUDGE_PROMPT = """You are an expert evaluator assessing the quality of an answer generated by a RAG (Retrieval-Augmented Generation) system.

Evaluate the answer on 4 dimensions, each scored from 1 to 5:

1. **Accuracy**: Is the answer factually correct based on the reference answer and key facts?
   - 5: Completely accurate, no factual errors
   - 3: Mostly accurate, minor errors
   - 1: Major factual errors or completely wrong
   Note: Use the reference answer ONLY as guidance, not for exact text matching.

2. **Groundedness**: Can each claim in the answer be directly mapped to the retrieved context?
   - 5: Every claim is directly supported by the retrieved context
   - 3: Most claims are directly supported, some cannot be mapped to the context
   - 1: Many claims cannot be mapped to the context (hallucinations)
   Note: For each claim in the answer, check whether it is directly supported by the retrieved context or not.

3. **Relevance**: Does the answer address the question asked?
   - 5: Directly and completely addresses the question
   - 3: Partially addresses the question
   - 1: Does not address the question

4. **Completeness**: Does the answer cover the key facts that should be present?
   - 5: All key facts are present
   - 3: Some key facts are present
   - 1: Most key facts are missing
   Note: Check whether each key fact from the list is present in the generated answer.

Additionally, identify the primary error type (if any):
- NONE: No significant errors
- HALLUCINATION: Answer contains claims not supported by the context
- MISATTRIBUTION: Claims are attributed to sources not in the retrieved context
- OMISSION: Relevant information present in the context is missing from the answer
- RETRIEVAL_FAIL: Poor retrieval quality affected the answer (relevant information was not in the retrieved context)

Question: {question}

Reference Answer (use as guidance only, not for exact matching):
{reference_answer}

Key Facts that should be present in the answer:
{key_facts}

Retrieved Context:
{context}

Generated Answer:
{generated_answer}

Respond ONLY with a JSON object in this exact format, no other text:
{{
  "accuracy": <1-5>,
  "groundedness": <1-5>,
  "relevance": <1-5>,
  "completeness": <1-5>,
  "error_type": "<NONE|HALLUCINATION|MISATTRIBUTION|OMISSION|RETRIEVAL_FAIL>",
  "reasoning": "<brief explanation of scores and error type>"
}}"""


# =========================
# Helpers
# =========================

def load_dataset(path: str) -> List[Dict]:
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def judge_answer(
    anthropic_client: anthropic.Anthropic,
    question: str,
    reference_answer: str,
    key_facts: List[str],
    chunks: List[Dict],
    generated_answer: str,
    retries: int = JUDGE_RETRIES,
) -> Optional[Dict[str, Any]]:
    """
    Evaluate the generated answer using Claude as judge.
    Retries on JSON parse failure. Returns None if all retries fail.
    """
    context = "\n\n---\n\n".join(
        f"[{i+1}] {c['metadata'].get('title', '')}\n{c['text']}"
        for i, c in enumerate(chunks)
    )
    key_facts_str = "\n".join(f"- {fact}" for fact in key_facts)

    prompt = JUDGE_PROMPT.format(
        question=question,
        reference_answer=reference_answer,
        key_facts=key_facts_str,
        context=context,
        generated_answer=generated_answer,
    )

    for attempt in range(retries + 1):
        try:
            response = anthropic_client.messages.create(
                model=JUDGE_MODEL,
                max_tokens=600,
                temperature=0,
                messages=[{"role": "user", "content": prompt}],
            )
            content = response.content[0].text.strip()
            content = content.replace("```json", "").replace("```", "").strip()
            return json.loads(content)
        except (json.JSONDecodeError, Exception) as e:
            if attempt < retries:
                print(f"    Judge retry {attempt + 1}/{retries} — {e}")
                time.sleep(1)
            else:
                print(f"    Judge failed after {retries + 1} attempts — skipping sample")
                return None

    return None


# =========================
# Retrieval Metrics
# =========================

def compute_hit(retrieved_ids: List[str], relevant_ids: List[str]) -> float:
    """Partial hit — at least one relevant chunk retrieved."""
    return 1.0 if any(rid in retrieved_ids for rid in relevant_ids) else 0.0


def compute_full_hit(retrieved_ids: List[str], relevant_ids: List[str]) -> float:
    """Full hit — all relevant chunks retrieved. Meaningful for multi-chunk questions."""
    return 1.0 if all(rid in retrieved_ids for rid in relevant_ids) else 0.0


def compute_rr(retrieved_ids: List[str], relevant_ids: List[str]) -> float:
    """Reciprocal rank of the first relevant chunk."""
    for i, rid in enumerate(retrieved_ids):
        if rid in relevant_ids:
            return 1.0 / (i + 1)
    return 0.0


def avg(lst: List[float]) -> float:
    return sum(lst) / len(lst) if lst else 0.0


# =========================
# Main
# =========================

def main() -> None:
    load_dotenv()

    openai_api_key = os.getenv("OPENAI_API_KEY")
    anthropic_api_key = os.getenv("ANTHROPIC_API_KEY")

    if not openai_api_key:
        raise ValueError("OPENAI_API_KEY not set.")
    if not anthropic_api_key:
        raise ValueError("ANTHROPIC_API_KEY not set.")

    openai_client = OpenAI(api_key=openai_api_key)
    anthropic_client = anthropic.Anthropic(api_key=anthropic_api_key)

    print("Loading dataset...")
    dataset = load_dataset(EVAL_DATASET_PATH)
    print(f"Questions: {len(dataset)}")

    print("Connecting to ChromaDB...")
    collection = get_collection(CHROMA_PATH, COLLECTION_NAME)
    print(f"Collection size: {collection.count()} chunks")

    os.makedirs(os.path.dirname(RESULTS_PATH), exist_ok=True)

    results = []
    hit_scores = []
    full_hit_scores = []
    rr_scores = []
    judge_scores = defaultdict(list)
    error_counts = defaultdict(int)
    total_latency = []
    skipped = 0

    for i, question in enumerate(dataset):
        qid = question["id"]
        qtype = question["type"]
        print(f"\n[{i+1}/{len(dataset)}] {qid} ({qtype})")
        print(f"  Q: {question['question'][:80]}...")

        start_time = time.time()

        # Retrieve
        chunks = retrieve(question["question"], collection, openai_client, TOP_K)
        retrieved_ids = [c["chunk_id"] for c in chunks]

        # Retrieval metrics
        relevant_ids = question["relevant_chunk_ids"]
        hit = compute_hit(retrieved_ids, relevant_ids)
        full_hit = compute_full_hit(retrieved_ids, relevant_ids)
        rr = compute_rr(retrieved_ids, relevant_ids)
        hit_scores.append(hit)
        full_hit_scores.append(full_hit)
        rr_scores.append(rr)

        # Generate
        prompt = build_prompt(question["question"], chunks)
        generated_answer = generate_answer(prompt, openai_client)
        print(f"  A: {generated_answer[:80]}...")

        # Judge
        scores = judge_answer(
            anthropic_client,
            question["question"],
            question["reference_answer"],
            question["key_facts"],
            chunks,
            generated_answer,
        )

        latency = time.time() - start_time
        total_latency.append(latency)

        if scores is None:
            skipped += 1
            print(f"  ⚠ Skipped judge — Hit: {hit:.0f} | RR: {rr:.2f}")
        else:
            for dim in ["accuracy", "groundedness", "relevance", "completeness"]:
                judge_scores[dim].append(scores.get(dim, 0))

            error_type = scores.get("error_type", "NONE")
            error_counts[error_type] += 1

            print(f"  Hit: {hit:.0f} | FullHit: {full_hit:.0f} | RR: {rr:.2f} | "
                  f"Acc:{scores.get('accuracy')} Grd:{scores.get('groundedness')} "
                  f"Rel:{scores.get('relevance')} Cmp:{scores.get('completeness')} "
                  f"| {error_type} | {latency:.1f}s")

        results.append({
            "id": qid,
            "type": qtype,
            "question": question["question"],
            "relevant_chunk_ids": relevant_ids,
            "retrieved_chunk_ids": retrieved_ids,
            "generated_answer": generated_answer,
            "reference_answer": question["reference_answer"],
            "key_facts": question["key_facts"],
            "hit": hit,
            "full_hit": full_hit,
            "reciprocal_rank": rr,
            "judge_scores": scores,
            "latency_seconds": round(latency, 2),
            "source_categories": question.get("source_categories", []),
        })

    # Per type breakdown
    by_type = defaultdict(lambda: defaultdict(list))
    for r in results:
        if r["judge_scores"] is None:
            continue
        t = r["type"]
        by_type[t]["hit"].append(r["hit"])
        by_type[t]["full_hit"].append(r["full_hit"])
        by_type[t]["rr"].append(r["reciprocal_rank"])
        for dim in ["accuracy", "groundedness", "relevance", "completeness"]:
            by_type[t][dim].append(r["judge_scores"].get(dim, 0))

    metrics = {
        "experiment": EXPERIMENT_NAME,
        "config": {
            "embedder": "text-embedding-3-small",
            "k": TOP_K,
            "generator": GENERATOR_MODEL,
            "judge": JUDGE_MODEL,
            "chunk_size": CHUNK_SIZE,
            "overlap": OVERLAP,
        },
        "overall": {
            "n_questions": len(results),
            "n_skipped": skipped,
            "hit_rate": avg(hit_scores),
            "full_hit_rate": avg(full_hit_scores),
            "mrr": avg(rr_scores),
            "accuracy": avg(judge_scores["accuracy"]),
            "groundedness": avg(judge_scores["groundedness"]),
            "relevance": avg(judge_scores["relevance"]),
            "completeness": avg(judge_scores["completeness"]),
            "avg_latency_seconds": round(avg(total_latency), 2),
            "error_distribution": dict(error_counts),
        },
        "by_type": {
            t: {
                "n": len(v["hit"]),
                "hit_rate": avg(v["hit"]),
                "full_hit_rate": avg(v["full_hit"]),
                "mrr": avg(v["rr"]),
                "accuracy": avg(v["accuracy"]),
                "groundedness": avg(v["groundedness"]),
                "relevance": avg(v["relevance"]),
                "completeness": avg(v["completeness"]),
            }
            for t, v in by_type.items()
        },
    }

    with open(RESULTS_PATH, "w", encoding="utf-8") as f:
        json.dump(results, f, ensure_ascii=False, indent=2)

    with open(METRICS_PATH, "w", encoding="utf-8") as f:
        json.dump(metrics, f, ensure_ascii=False, indent=2)

    print("\n" + "=" * 60)
    print(f"Evaluation complete — {EXPERIMENT_NAME}")
    print(f"Questions      : {len(results)} ({skipped} skipped)")
    print(f"Hit Rate       : {metrics['overall']['hit_rate']:.3f}")
    print(f"Full Hit Rate  : {metrics['overall']['full_hit_rate']:.3f}")
    print(f"MRR            : {metrics['overall']['mrr']:.3f}")
    print(f"Accuracy       : {metrics['overall']['accuracy']:.2f}")
    print(f"Groundedness   : {metrics['overall']['groundedness']:.2f}")
    print(f"Relevance      : {metrics['overall']['relevance']:.2f}")
    print(f"Completeness   : {metrics['overall']['completeness']:.2f}")
    print(f"Avg Latency    : {metrics['overall']['avg_latency_seconds']:.2f}s")
    print(f"\nError distribution:")
    for err, count in sorted(error_counts.items()):
        print(f"  {err:<20} {count}")
    print(f"\nResults : {RESULTS_PATH}")
    print(f"Metrics : {METRICS_PATH}")
    print("=" * 60)


if __name__ == "__main__":
    main()